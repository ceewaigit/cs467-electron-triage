"""The watchdog must alert when requested writes are missing and stay quiet otherwise."""
import importlib.util
import pathlib
import unittest

ROOT = pathlib.Path(__file__).resolve().parents[1]
SPEC = importlib.util.spec_from_file_location("check_triage_run", ROOT / "scripts/check_triage_run.py")
WATCHDOG = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(WATCHDOG)

RUN = {"id": 42, "conclusion": "success"}
CLEAN = {"prompt_injection": False, "secret_leak": False, "malicious_patch": False}
OUTPUT = {"items": [{"type": "add_labels", "labels": [{"name": "component/gpu", "confidence": "MEDIUM"}]},
                    {"type": "triage_comment", "kinds": "need-repro", "refs": ""}]}
POSTED = [{"user": {"login": WATCHDOG.BOT}, "body": "text\n> Generated by [Issue triage](https://x/actions/runs/42)."}]


class Watchdog(unittest.TestCase):
    def test_delivered_writes_raise_no_alert(self):
        problems, notes = WATCHDOG.check(RUN, True, [], OUTPUT, CLEAN, {"component/gpu", "bug"}, POSTED)
        self.assertEqual(problems, [])
        self.assertIn("Every requested write is on the issue.", notes)

    def test_withheld_or_suggested_label_and_missing_comment_alert(self):
        problems, _ = WATCHDOG.check(RUN, True, [], OUTPUT, None, {"bug"}, [])
        self.assertEqual(len(problems), 2)
        self.assertIn("`component/gpu`", problems[0])

    def test_comment_from_another_run_does_not_count(self):
        other = [{"user": {"login": WATCHDOG.BOT}, "body": "see /actions/runs/7"}]
        problems, _ = WATCHDOG.check(RUN, True, [], OUTPUT, CLEAN, {"component/gpu"}, other)
        self.assertEqual(problems, ["The requested triage comment is not on the issue."])

    def test_reviewer_rejection_is_reported_not_alerted(self):
        problems, notes = WATCHDOG.check(RUN, True, [{"state": "rejected"}], OUTPUT, CLEAN, set(), [])
        self.assertEqual(problems, [])
        self.assertTrue(any("rejected" in note for note in notes))
        self.assertNotIn("Every requested write is on the issue.", notes)

    def test_successful_run_without_output_alerts(self):
        problems, _ = WATCHDOG.check(RUN, True, [], None, CLEAN, set(), [])
        self.assertEqual(len(problems), 1)

    def test_run_whose_agent_never_started_needs_nothing(self):
        problems, _ = WATCHDOG.check(RUN, False, [], None, None, set(), [])
        self.assertEqual(problems, [])

    def test_noop_needs_nothing(self):
        problems, _ = WATCHDOG.check(RUN, True, [], {"items": [{"type": "noop", "message": "skip"}]}, CLEAN, set(), [])
        self.assertEqual(problems, [])


if __name__ == "__main__":
    unittest.main()
