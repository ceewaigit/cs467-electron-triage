"""The watchdog must alert when requested writes are missing and stay quiet otherwise."""
import importlib.util
import pathlib
import unittest

ROOT = pathlib.Path(__file__).resolve().parents[1]
SPEC = importlib.util.spec_from_file_location("check_triage_run", ROOT / "scripts/check_triage_run.py")
WATCHDOG = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(WATCHDOG)

RUN = {"id": 42, "conclusion": "success"}
CLEAN = {"prompt_injection": False, "secret_leak": False, "malicious_patch": False}
OUTPUT = {"items": [{"type": "add_labels", "labels": [{"name": "component/gpu", "confidence": "HIGH"}]},
                    {"type": "triage_comment", "kinds": "need-repro", "refs": ""}]}
SUGGESTED = {"items": [{"type": "add_labels", "labels": [{"name": "component/gpu", "confidence": "MEDIUM"}]}]}
POSTED = [{"user": {"login": WATCHDOG.BOT}, "body": "text\n> Generated by [Issue triage](https://x/actions/runs/42)."}]
RAN = {"activation": "success", "agent": "success"}


class Watchdog(unittest.TestCase):
    def test_delivered_writes_raise_no_alert(self):
        problems, notes = WATCHDOG.check(RUN, RAN, [], OUTPUT, CLEAN, {"component/gpu", "bug"}, POSTED)
        self.assertEqual(problems, [])
        self.assertIn("Every requested write is on the issue.", notes)

    def test_withheld_label_and_missing_comment_alert(self):
        problems, _ = WATCHDOG.check(RUN, RAN, [], OUTPUT, None, {"bug"}, [])
        self.assertEqual(len(problems), 2)
        self.assertIn("`component/gpu`", problems[0])

    def test_label_with_no_confidence_alerts_when_missing(self):
        output = {"items": [{"type": "add_labels", "labels": ["component/gpu"]}]}
        problems, _ = WATCHDOG.check(RUN, RAN, [], output, CLEAN, set(), [])
        self.assertEqual(len(problems), 1)

    def test_suggestion_is_reported_not_alerted(self):
        problems, notes = WATCHDOG.check(RUN, RAN, [], SUGGESTED, CLEAN, set(), [])
        self.assertEqual(problems, [])
        self.assertTrue(any("suggestions" in note for note in notes))
        self.assertNotIn("Every requested write is on the issue.", notes)

    def test_medium_label_without_a_verdict_counts_as_withheld(self):
        problems, _ = WATCHDOG.check(RUN, RAN, [], SUGGESTED, None, set(), [])
        self.assertEqual(len(problems), 1)

    def test_comment_from_another_run_does_not_count(self):
        other = [{"user": {"login": WATCHDOG.BOT}, "body": "see /actions/runs/7"}]
        problems, _ = WATCHDOG.check(RUN, RAN, [], OUTPUT, CLEAN, {"component/gpu"}, other)
        self.assertEqual(problems, ["The requested triage comment is not on the issue."])

    def test_reviewer_rejection_is_reported_not_alerted(self):
        failed = {"id": 42, "conclusion": "failure"}
        problems, notes = WATCHDOG.check(failed, RAN, [{"state": "rejected"}], OUTPUT, CLEAN, set(), [])
        self.assertEqual(problems, [])
        self.assertTrue(any("rejected" in note for note in notes))
        self.assertNotIn("Every requested write is on the issue.", notes)

    def test_successful_run_without_output_alerts(self):
        problems, _ = WATCHDOG.check(RUN, RAN, [], None, CLEAN, set(), [])
        self.assertEqual(len(problems), 1)

    def test_failed_run_alerts_even_with_no_output(self):
        failed = {"id": 42, "conclusion": "failure"}
        for jobs in (RAN, {"activation": "success", "agent": "failure"}, {"activation": "failure", "agent": None}):
            with self.subTest(jobs=jobs):
                problems, _ = WATCHDOG.check(failed, jobs, [], None, None, set(), [])
                self.assertEqual(len(problems), 1)

    def test_cancelled_run_needs_nothing(self):
        problems, _ = WATCHDOG.check({"id": 42, "conclusion": "cancelled"}, RAN, [], OUTPUT, None, set(), [])
        self.assertEqual(problems, [])

    def test_daily_cap_skip_is_listed(self):
        jobs = {"pre_activation": "success", "activation": "success", "agent": "skipped"}
        problems, _ = WATCHDOG.check(RUN, jobs, [], None, None, set(), [])
        self.assertEqual(problems, [WATCHDOG.CAP_SKIP])

    def test_maintainer_issue_stopped_at_pre_activation_needs_nothing(self):
        jobs = {"pre_activation": "success", "activation": "skipped", "agent": "skipped"}
        problems, _ = WATCHDOG.check(RUN, jobs, [], None, None, set(), [])
        self.assertEqual(problems, [])

    def test_noop_needs_nothing(self):
        problems, _ = WATCHDOG.check(RUN, RAN, [], {"items": [{"type": "noop", "message": "skip"}]}, CLEAN, set(), [])
        self.assertEqual(problems, [])


if __name__ == "__main__":
    unittest.main()
