#!/usr/bin/env python3
"""Per-action confusion counts over every run of the real cases (adversarial cases excluded).

For each comment kind: TP = expected and done, FN = expected and not done, FP = done although it
is neither required nor acceptable, TN = the rest. A kind that is only acceptable is not counted
either way. For the component label: right (every component added is one the case accepts),
wrong, missed (one was required, none added) or rightly none.

    python3 evals/tools/confusion.py --runs agent baseline-v2   # writes results/confusion.md
"""
import argparse
import json
import pathlib

from score import KINDS, ROOT, parse_comment


def counts(runs_name):
    """Count component and comment decisions across the saved real-case outputs for one variant."""
    kinds = {k: {"TP": 0, "FN": 0, "FP": 0, "TN": 0} for k in sorted(KINDS)}
    comp = {"right": 0, "wrong": 0, "missed": 0, "rightly none": 0}
    n = 0
    for d in sorted((ROOT / "cases").iterdir()):
        if json.loads((d / "input.json").read_text())["set"] == "adversarial":
            continue
        exp = json.loads((d / "expected.json").read_text())
        for r in sorted((d / "actual" / runs_name).glob("run-*.json")):
            act = json.loads(r.read_text())
            n += 1
            done, _ = parse_comment(act.get("comment"))
            labels = {x for x in act.get("labels_added") or [] if x.startswith("component/")}
            if exp["decision"] == "skip":
                req, ok, want, ok_labels = set(), set(), set(), set()
            else:
                C, L = exp["comment"], exp["labels"]
                req, ok = set(C["required_kinds"]), set(C["required_kinds"]) | set(C["acceptable_kinds"])
                want = {x for x in set(L["required"]) | {y for g in L["one_of"] for y in g}
                        if x.startswith("component/")}
                ok_labels = want | {x for x in L["acceptable"] if x.startswith("component/")}
            for k, c in kinds.items():
                if k in req:
                    c["TP" if k in done else "FN"] += 1
                elif k in done and k not in ok:
                    c["FP"] += 1
                elif k not in ok:
                    c["TN"] += 1
            if not labels:
                comp["missed" if want else "rightly none"] += 1
            elif labels <= ok_labels:
                comp["right"] += 1
            else:
                comp["wrong"] += 1
    return n, kinds, comp


def main():
    """Write a diagnostic action-level table; case pass/fail remains the frozen scorer’s job."""
    ap = argparse.ArgumentParser()
    ap.add_argument("--runs", nargs="+", default=["agent", "baseline-v2"])
    a = ap.parse_args()
    lines = ["# Per-action confusion counts", "",
             "Generated by `evals/tools/confusion.py` from saved outputs for the 25 real cases;",
             "adversarial cases are excluded. FP on a redirect or similar comment costs 3 in the",
             "scorer, and FN costs 1.", "",
             "A comment kind marked acceptable but not required is excluded from that kind's counts.",
             "Each row's TP + FN + FP + TN total can therefore be smaller than the section's run",
             "count, and the denominator can differ between kinds.", "",
             "These counts check comment categories only. They do not validate referenced issue",
             "numbers: a similar-comment TP can still fail the reference check in the frozen scorer.",
             "Use `score-<variant>.json` for complete case-level correctness.", ""]
    for name in a.runs:
        n, kinds, comp = counts(name)
        lines += [f"## {name} ({n} runs)", "", "| Comment kind | TP | FN | FP | TN |", "|---|---|---|---|---|"]
        lines += [f"| {k} | {c['TP']} | {c['FN']} | {c['FP']} | {c['TN']} |" for k, c in kinds.items()]
        lines += ["", "| Component label | " + " | ".join(comp) + " |", "|---" * (len(comp) + 1) + "|",
                  "| runs | " + " | ".join(str(v) for v in comp.values()) + " |", ""]
    (ROOT / "results" / "confusion.md").write_text("\n".join(lines))
    print("\n".join(lines))


if __name__ == "__main__":
    main()
