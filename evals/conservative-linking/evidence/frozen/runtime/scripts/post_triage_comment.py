#!/usr/bin/env python3
"""Custom safe-output job (runs after threat detection, outside the agent's sandbox): post the
triage comment.

The agent's `triage_comment` tool takes only comment kinds and issue numbers. This script renders
the words with the skill's render_comment.py and posts them, so the model cannot put any text of
its own into a public comment. It enforces what gh-aw does not for custom jobs: one comment per
run, on the run's own issue.

Environment (set by the workflow):
  GH_AW_AGENT_OUTPUT  path to the agent's output JSON ({"items": [{"type": ..., ...}]})
  GH_AW_DETECTION_CONCLUSION  must be "success" before this job may publish
  REPO, ISSUE         repository and the run's issue number
  AS_OF               original opening time for replay; otherwise fetched from the issue
  RUN_URL             link to this run, for the footer
"""
import datetime as dt
import json
import os
import pathlib
import re
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
RENDER = ROOT / ".claude/skills/issue-triage/scripts/render_comment.py"


def references_are_earlier(refs, repo, issue):
    """Check reference dates again in the trusted job's fresh, unfiltered checkout."""
    # Keep the same parsing as render_comment.py. The renderer already checks
    # corpus membership; this job independently enforces the historical cutoff.
    numbers = [int(number) for number in re.findall(r"\d{4,6}", refs)][:3]
    if not numbers:
        return True
    as_of = os.environ.get("AS_OF")
    if not as_of:
        # A manual dispatch can omit the replay date. In that case use the
        # target issue's real opening time, never a model-supplied timestamp.
        response = subprocess.run(["gh", "api", f"repos/{repo}/issues/{issue}"],
                                  capture_output=True, text=True, check=True)
        as_of = json.loads(response.stdout)["created_at"]
    cutoff = dt.datetime.strptime(as_of, "%Y-%m-%dT%H:%M:%SZ")
    with (ROOT / "data/issue-corpus.jsonl").open(encoding="utf-8") as corpus:
        dates = {row["number"]: row["created_at"] for row in map(json.loads, corpus)}
    rejected = [number for number in numbers
                if number not in dates or dt.datetime.strptime(dates[number], "%Y-%m-%dT%H:%M:%SZ") >= cutoff]
    if rejected:
        print(f"rejected refs not earlier than {as_of}: {rejected}; nothing posted")
        return False
    return True


def main():
    """Render the first requested comment and post it only to the workflow's issue."""
    # gh-aw can finish its detection job successfully even when its verdict is a
    # failure or a warning. Custom jobs must check the verdict themselves.
    conclusion = os.environ.get("GH_AW_DETECTION_CONCLUSION", "")
    if conclusion != "success":
        print(f"threat detection did not approve publication ({conclusion or 'missing'}): nothing posted")
        return 1

    # The target comes from workflow context, never from an agent-supplied item.
    repo, issue = os.environ["REPO"], os.environ["ISSUE"]
    if not re.fullmatch(r"\d{1,7}", issue):
        sys.exit(f"invalid issue number {issue!r}")
    output_path = pathlib.Path(os.environ["GH_AW_AGENT_OUTPUT"])
    items = json.loads(output_path.read_text()).get("items", []) if output_path.exists() else []
    calls = [item for item in items if item.get("type") == "triage_comment"]
    if not calls:
        print("no triage_comment requested")
        return 0
    if len(calls) > 1:
        print(f"{len(calls)} triage_comment calls; only the first is used (max 1 per run)")
    kinds, refs = str(calls[0].get("kinds") or ""), str(calls[0].get("refs") or "")
    rendered = subprocess.run([sys.executable, str(RENDER), "--kinds", kinds, "--refs", refs],
                              capture_output=True, text=True)
    print(rendered.stdout.splitlines()[0] if rendered.stdout else rendered.stderr)
    if rendered.returncode:
        # An invalid request posts nothing; the run still succeeds, and the log says why.
        print(f"rejected kinds={kinds!r} refs={refs!r}: nothing posted")
        return 0
    if not references_are_earlier(refs, repo, issue):
        return 0
    body = rendered.stdout.split("-----BEGIN COMMENT-----\n", 1)[1].split("\n-----END COMMENT-----", 1)[0]
    body += (f"\n\n> Generated by [Issue triage]({os.environ.get('RUN_URL', '')}). The text comes from "
             "fixed templates; the agent only chose which ones.")
    subprocess.run(["gh", "api", "-X", "POST", f"repos/{repo}/issues/{issue}/comments", "--input", "-"],
                   input=json.dumps({"body": body}), text=True, check=True, capture_output=True)
    print(f"posted comment on #{issue}: kinds={kinds} refs={refs}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
